# 6. FIGURE 04: JJAS VS ON ANOMALIES
# ==========================================================

def plot_jjas_on_anomalies(
    data, config, logger
):
    trans = data["transitions"].copy()

    trans = trans[
        trans["JJAS_anomaly_pct"].notna()
        & trans["ON_anomaly_pct"].notna()
    ].sort_values("year")

    years = trans["year"].to_numpy()

    jjas = trans["JJAS_anomaly_pct"].to_numpy()
    on = trans["ON_anomaly_pct"].to_numpy()

    x = np.arange(len(years))
    width = 0.40

    fig, ax = plt.subplots(figsize=(15, 7))

    ax.bar(
        x - width / 2,
        jjas,
        width=width,
        color=DRY_COLOR,
        label="June–September (JJAS)",
    )

    ax.bar(
        x + width / 2,
        on,
        width=width,
        color=WET_COLOR,
        label="October–November (ON)",
    )

    ax.axhline(
        0, color=DARK_COLOR, linewidth=1
    )

    ax.set_xticks(x)
    ax.set_xticklabels(
        years,
        rotation=60,
        ha="right",
        fontsize=9,
    )

    ax.set_title(
        "Rwanda Dry-Season and Short-Rains Anomalies\n"
        "June–September versus October–November",
        fontweight="bold",
    )

    ax.set_xlabel("Year")
    ax.set_ylabel("Seasonal rainfall anomaly (%)")

    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, loc="upper left")

    # Highlight detected dry-to-wet reversal years.
    reversal = (
        trans["dry_to_wet_reversal"]
        .astype(str).str.lower() == "true"
    )

    for index, flag in enumerate(reversal):
        if flag:
            ax.axvspan(
                index - 0.5,
                index + 0.5,
                color=HIGHLIGHT_COLOR,
                alpha=0.10,
            )

    fig.tight_layout()

    save_figure(
        fig,
        "04_JJAS_ON_rainfall_anomalies.png",
        config,
        logger,
    )


