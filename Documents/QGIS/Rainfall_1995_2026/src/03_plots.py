# 5. FIGURE 03: MONTHLY ANOMALY HEATMAP
# ==========================================================

def plot_anomaly_heatmap(
    data, ref_start, ref_end, config, logger
):
    monthly = data["monthly"]

    pivot = monthly.pivot(
        index="year",
        columns="month",
        values="anomaly_pct",
    )

    pivot = pivot.reindex(
        columns=range(1, 13)
    )

    years = pivot.index.to_numpy()
    matrix = pivot.to_numpy(dtype=float)

    # Symmetric color range, capped at 150%
    # for consistent visual comparison.
    finite = np.abs(matrix[np.isfinite(matrix)])

    max_abs = (
        min(max(np.nanpercentile(finite, 95), 50), 150)
        if len(finite)
        else 100
    )

    norm = TwoSlopeNorm(
        vmin=-max_abs,
        vcenter=0,
        vmax=max_abs,
    )

    cmap = plt.get_cmap("RdBu").copy()
    cmap.set_bad(color="#E0E0E0")

    fig, ax = plt.subplots(figsize=(13, 11))

    image = ax.imshow(
        np.ma.masked_invalid(matrix),
        cmap=cmap,
        norm=norm,
        aspect="auto",
        interpolation="nearest",
    )

    ax.set_xticks(range(12))
    ax.set_xticklabels(MONTH_LABELS)

    step = 2
    ax.set_yticks(range(0, len(years), step))
    ax.set_yticklabels(years[::step])

    ax.axvline(
        4.5,
        color="black",
        linewidth=1,
        alpha=0.45,
    )
    ax.axvline(
        8.5,
        color="black",
        linewidth=1,
        alpha=0.45,
    )
    ax.axvline(
        10.5,
        color="black",
        linewidth=1,
        alpha=0.45,
    )

    ax.set_title(
        "Rwanda Monthly Rainfall Anomalies\n"
        f"Relative to {ref_start}–{ref_end} climatology",
        fontweight="bold",
        pad=15,
    )

    ax.set_xlabel("Month")
    ax.set_ylabel("Year")

    colorbar = fig.colorbar(
        image,
        ax=ax,
        shrink=0.78,
        pad=0.02,
        extend="both",
    )
    colorbar.set_label("Rainfall anomaly (%)")

    fig.text(
        0.5, 0.015,
        "Brown/red = below average; "
        "blue = above average; "
        "grey = unavailable. "
        "Values beyond the color scale are saturated.",
        ha="center",
        fontsize=9,
    )

    fig.tight_layout(rect=[0, 0.035, 1, 1])

    save_figure(
        fig,
        "03_monthly_rainfall_anomaly_heatmap.png",
        config,
        logger,
    )


