# 8. FIGURE 06: HISTORICAL EVENT COMPARISON
# ==========================================================

def plot_historical_comparison(
    data, ref_start, ref_end, config, logger
):
    monthly = data["monthly"]
    clim = data["climatology"].sort_values("month")

    means = clim["mean_mm"].to_numpy()
    months = np.arange(1, 13)

    fig, axes = plt.subplots(
        len(EVENT_YEARS),
        1,
        figsize=(13, 14),
        sharex=True,
        sharey=True,
    )

    max_value = float(
        monthly["rainfall_mm"].max()
    )

    for ax, year in zip(axes, EVENT_YEARS):
        subset = monthly[
            monthly["year"] == year
        ].sort_values("month")

        values = (
            subset.set_index("month")["rainfall_mm"]
            .reindex(months)
            .to_numpy()
        )

        ax.axvspan(
            5.5, 9.5,
            color=DRY_COLOR,
            alpha=0.09,
        )

        ax.bar(
            months,
            values,
            color=[
                DRY_COLOR if m in [6, 7, 8, 9]
                else WET_COLOR
                for m in months
            ],
            alpha=0.80,
            width=0.7,
        )

        ax.plot(
            months,
            means,
            color=HIGHLIGHT_COLOR,
            linestyle="--",
            linewidth=1.8,
            marker="o",
            markersize=3,
        )

        ax.text(
            0.015, 0.90,
            str(year),
            transform=ax.transAxes,
            ha="left",
            va="top",
            fontsize=12,
            fontweight="bold",
        )

        ax.set_ylabel("Rainfall (mm)")
        ax.set_ylim(0, max_value * 1.15)
        ax.set_xlim(0.5, 12.5)
        ax.grid(axis="y", alpha=0.2)

    axes[-1].set_xticks(months)
    axes[-1].set_xticklabels(MONTH_LABELS)
    axes[-1].set_xlabel("Month")

    fig.suptitle(
        "Rwanda Monthly Rainfall During Selected "
        "Historical Climate Years\n"
        f"CHIRPS v3 versus {ref_start}–{ref_end} climatology",
        fontsize=15,
        fontweight="bold",
        y=0.998,
    )

    fig.legend(
        handles=[
            Patch(color=WET_COLOR, label="Monthly rainfall"),
            plt.Line2D(
                [0], [0],
                color=HIGHLIGHT_COLOR,
                linestyle="--",
                marker="o",
                label="Historical monthly mean",
            ),
            Patch(
                facecolor=DRY_COLOR,
                alpha=0.20,
                label="JJAS period",
            ),
        ],
        loc="lower center",
        ncol=3,
        frameon=False,
        bbox_to_anchor=(0.5, 0.005),
    )

    fig.tight_layout(rect=[0, 0.04, 1, 0.97])

    save_figure(
        fig,
        "06_historical_event_comparison.png",
        config,
        logger,
    )


# ==========================================================
# 9. MAIN
# ==========================================================

def main():
    parser = argparse.ArgumentParser(
        description="Generate Rwanda CHIRPS rainfall plots"
    )

    parser.add_argument(
        "--figure",
        type=int,
        choices=[1, 2, 3, 4, 5, 6],
        default=None,
        help="Generate only one figure (1–6)",
    )

    args = parser.parse_args()

    config = load_config()
    ensure_directories(config)
    configure_style()

    logger = setup_logger(
        name="rainfall_plots",
        logfile="rainfall_plots.log",
    )

    data, ref_start, ref_end = load_tables(config)

    logger.info(
        "Loaded monthly, annual, seasonal "
        "and transition tables."
    )

    tasks = {
        1: lambda: plot_monthly_climatology(
            data, ref_start, ref_end, config, logger
        ),
        2: lambda: plot_annual_trend(
            data, ref_start, ref_end, config, logger
        ),
        3: lambda: plot_anomaly_heatmap(
            data, ref_start, ref_end, config, logger
        ),
        4: lambda: plot_jjas_on_anomalies(
            data, config, logger
        ),
        5: lambda: plot_reversals(
            data, config, logger
        ),
        6: lambda: plot_historical_comparison(
            data, ref_start, ref_end, config, logger
        ),
    }

    selected = (
        [args.figure]
        if args.figure is not None
        else list(tasks)
    )

    for number in selected:
        logger.info(
            "Generating figure %02d ...",
            number,
        )
        tasks[number]()

    logger.info(
        "Successfully completed %d figure(s).",
        len(selected),
    )


if __name__ == "__main__":
    main()
