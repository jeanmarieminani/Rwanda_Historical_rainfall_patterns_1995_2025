# 7. FIGURE 05: DRY-TO-WET REVERSALS
# ==========================================================

def plot_reversals(data, config, logger):
    trans = data["transitions"].copy()

    trans = trans.dropna(
        subset=[
            "JJAS_anomaly_pct",
            "ON_anomaly_pct",
        ]
    )

    x = trans["JJAS_anomaly_pct"].to_numpy()
    y = trans["ON_anomaly_pct"].to_numpy()
    years = trans["year"].to_numpy()

    reversal = (
        trans["dry_to_wet_reversal"]
        .astype(str).str.lower() == "true"
    ).to_numpy()

    fig, ax = plt.subplots(figsize=(11, 8))

    ax.axvline(
        0, color=NORMAL_COLOR,
        linestyle="--", linewidth=1
    )
    ax.axhline(
        0, color=NORMAL_COLOR,
        linestyle="--", linewidth=1
    )

    ax.scatter(
        x[~reversal],
        y[~reversal],
        s=65,
        color=WET_COLOR,
        alpha=0.75,
        edgecolors="white",
        linewidths=0.6,
        label="Other complete years",
    )

    if reversal.any():
        ax.scatter(
            x[reversal],
            y[reversal],
            s=170,
            marker="*",
            color=HIGHLIGHT_COLOR,
            edgecolors="black",
            linewidths=0.5,
            zorder=5,
            label="Detected dry-to-wet reversal",
        )

    # Show both years of interest and detected reversals.
    label_years = set(EVENT_YEARS)

    for xx, yy, year, flag in zip(
        x, y, years, reversal
    ):
        if year in label_years or flag:
            ax.annotate(
                str(year),
                (xx, yy),
                xytext=(6, 6),
                textcoords="offset points",
                fontsize=9,
                fontweight="bold" if flag else "normal",
            )

    # Percentile thresholds from observed
    # JJAS and ON rainfall are not constant
    # percentage thresholds unless normalized.
    # We identify reversals using the CSV flags.
    ax.set_title(
        "Rwanda Dry-to-Wet Seasonal Transitions\n"
        "CHIRPS v3 | Complete years only",
        fontweight="bold",
    )

    ax.set_xlabel(
        "June–September rainfall anomaly (%)"
    )
    ax.set_ylabel(
        "October–November rainfall anomaly (%)"
    )

    ax.grid(alpha=0.20)

    ax.legend(
        loc="best",
        frameon=False,
    )

    fig.tight_layout()

    save_figure(
        fig,
        "05_dry_to_wet_reversals.png",
        config,
        logger,
    )


