# 4. FIGURE 02: ANNUAL RAINFALL TREND
# ==========================================================

def plot_annual_trend(
    data, ref_start, ref_end, config, logger
):
    annual = data["annual"].copy()

    annual["complete"] = (
        annual["complete"].astype(str).str.lower()
        == "true"
    )

    annual = annual[
        annual["complete"]
        & annual["rainfall_sum_mm"].notna()
    ].copy()

    annual = annual.sort_values("year")

    years = annual["year"].to_numpy()
    values = annual["rainfall_sum_mm"].to_numpy()

    if len(annual) < 3:
        raise ValueError(
            "At least three complete years are required."
        )

    regression = linregress(years, values)

    trend = (
        regression.intercept
        + regression.slope * years
    )

    baseline = data["annual"][
        data["annual"]["year"].between(
            ref_start, ref_end
        )
    ]["rainfall_sum_mm"].mean()

    fig, ax = plt.subplots(figsize=(13, 6))

    colors = [
        WET_COLOR if value >= baseline
        else DRY_COLOR
        for value in values
    ]

    ax.bar(
        years, values,
        color=colors,
        width=0.78,
        alpha=0.85,
    )

    ax.plot(
        years, trend,
        color=HIGHLIGHT_COLOR,
        linewidth=2.5,
        label="Linear trend",
    )

    ax.axhline(
        baseline,
        color=DARK_COLOR,
        linestyle="--",
        linewidth=1.5,
        label=f"Reference mean: {baseline:.1f} mm",
    )

    ax.set_title(
        "Rwanda Annual Rainfall and Linear Trend\n"
        f"CHIRPS v3 | {years.min()}–{years.max()}",
        fontweight="bold",
    )

    ax.set_xlabel("Year")
    ax.set_ylabel("Annual rainfall (mm)")

    tick_years = list(range(
        (int(years.min()) // 5) * 5,
        int(years.max()) + 1,
        5,
    ))

    tick_years = [
        year for year in tick_years
        if years.min() <= year <= years.max()
    ]

    ax.set_xticks(tick_years)
    ax.set_xlim(years.min() - 1, years.max() + 1)
    ax.grid(axis="y", alpha=0.25)

    ax.legend(loc="upper left", frameon=False)

    statistics = (
        f"Trend: {regression.slope:+.2f} mm/year\n"
        f"R² = {regression.rvalue**2:.3f}\n"
        f"p = {regression.pvalue:.4f}\n"
        f"n = {len(annual)} years"
    )

    ax.text(
        0.98, 0.96,
        statistics,
        transform=ax.transAxes,
        ha="right",
        va="top",
        fontsize=10,
        bbox={
            "facecolor": "white",
            "edgecolor": "#DDDDDD",
            "boxstyle": "round,pad=0.5",
        },
    )

    fig.tight_layout()

    save_figure(
        fig,
        "02_annual_rainfall_trend.png",
        config,
        logger,
    )

    logger.info(
        "Annual trend: %.3f mm/year | "
        "R2=%.4f | p=%.5f",
        regression.slope,
        regression.rvalue**2,
        regression.pvalue,
    )


