# ==========================================================
# 1. CONFIGURATION AND STYLE
# ==========================================================

DRY_COLOR = "#C78335"
WET_COLOR = "#2879B9"
NORMAL_COLOR = "#718096"
DARK_COLOR = "#263238"
HIGHLIGHT_COLOR = "#B02A37"

EVENT_YEARS = [1997, 2015, 2019, 2023, 2024]

MONTH_LABELS = [
    "Jan", "Feb", "Mar", "Apr", "May", "Jun",
    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"
]


def configure_style():
    plt.rcParams.update({
        "figure.dpi": 120,
        "savefig.dpi": 300,
        "font.family": "DejaVu Sans",
        "font.size": 10,
        "axes.titlesize": 14,
        "axes.labelsize": 11,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.grid": False,
        "figure.facecolor": "white",
        "axes.facecolor": "white",
        "savefig.facecolor": "white",
    })


def save_figure(fig, filename, config, logger):
    directory = project_path(
        config["paths"]["figures"]
    )
    directory.mkdir(parents=True, exist_ok=True)

    path = directory / filename

    dpi = int(
        config["visualization"]["figure_dpi"]
    )

    fig.savefig(
        path,
        dpi=dpi,
        bbox_inches="tight",
        facecolor="white",
    )

    plt.close(fig)
    logger.info("Saved figure: %s", path)


# ==========================================================
# 2. LOAD DATA
# ==========================================================

def load_tables(config):
    project = config["project"]
    climate = config["climatology"]

    start = int(project["start_year"])
    end = int(project["end_year"])

    ref_start = int(climate["reference_start_year"])
    ref_end = int(climate["reference_end_year"])

    tables = project_path(
        config["paths"]["tables"]
    )

    filenames = {
        "monthly":
            f"rwanda_monthly_rainfall_{start}_{end}.csv",

        "annual":
            f"rwanda_annual_rainfall_{start}_{end}.csv",

        "seasonal":
            f"rwanda_seasonal_rainfall_{start}_{end}.csv",

        "climatology":
            f"rwanda_monthly_climatology_"
            f"{ref_start}_{ref_end}.csv",

        "transitions":
            f"rwanda_dry_wet_transitions_"
            f"{start}_{end}.csv",
    }

    data = {}

    for key, filename in filenames.items():
        path = tables / filename

        if not path.exists():
            raise FileNotFoundError(
                f"Missing input file: {path}\n"
                "Run 02_build_series.py first."
            )

        data[key] = pd.read_csv(path)

    for key in ("monthly", "annual", "seasonal",
                "transitions"):
        data[key]["year"] = pd.to_numeric(
            data[key]["year"]
        ).astype(int)

    data["monthly"]["month"] = pd.to_numeric(
        data["monthly"]["month"]
    ).astype(int)

    data["climatology"]["month"] = pd.to_numeric(
        data["climatology"]["month"]
    ).astype(int)

    return data, ref_start, ref_end


# ==========================================================
# 3. FIGURE 01: MONTHLY RAINFALL CLIMATOLOGY
# ==========================================================

def plot_monthly_climatology(
    data, ref_start, ref_end, config, logger
):
    clim = data["climatology"].sort_values("month")

    months = clim["month"].to_numpy()
    means = clim["mean_mm"].to_numpy()

    fig, ax = plt.subplots(figsize=(12, 6))

    colors = [
        DRY_COLOR if month in [6, 7, 8, 9]
        else WET_COLOR
        for month in months
    ]

    ax.bar(
        months,
        means,
        color=colors,
        edgecolor="white",
        linewidth=0.8,
        width=0.72,
    )

    ax.axvspan(
        5.5, 9.5,
        color=DRY_COLOR,
        alpha=0.09,
        zorder=0,
    )

    for x, y in zip(months, means):
        ax.text(
            x, y + max(means) * 0.015,
            f"{y:.1f}",
            ha="center",
            va="bottom",
            fontsize=9,
        )

    ax.set_title(
        "Rwanda Monthly Rainfall Climatology\n"
        f"CHIRPS v3 | {ref_start}–{ref_end}",
        fontweight="bold",
    )

    ax.set_xlabel("Month")
    ax.set_ylabel("Mean monthly rainfall (mm)")
    ax.set_xticks(range(1, 13))
    ax.set_xticklabels(MONTH_LABELS)
    ax.set_xlim(0.5, 12.5)
    ax.set_ylim(0, max(means) * 1.18)

    ax.grid(axis="y", alpha=0.25)

    ax.legend(
        handles=[
            Patch(color=DRY_COLOR, label="June–September"),
            Patch(color=WET_COLOR, label="Other months"),
        ],
        loc="upper right",
        frameon=False,
    )

    fig.tight_layout()

    save_figure(
        fig,
        "01_monthly_rainfall_climatology.png",
        config,
        logger,
    )


